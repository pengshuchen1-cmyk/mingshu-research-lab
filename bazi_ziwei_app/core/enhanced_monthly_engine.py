CLASH_WARNING = "注意：本月地支有冲，需防范突发变化和人际冲突，重大决策宜谨慎。"


def get_enhanced_events(ten_god, relation):
    """根据十神和喜忌关系获取增强的事件描述。"""
    events = EVENT_DETAILS.get(ten_god, {})
    if relation in events:
        return events[relation]
    return ["稳步推进当前事务，务实为主。"]


def get_direction(ten_god):
    """获取本月大方向/主题。"""
    return TEN_GOD_DIRECTION.get(ten_god, "务实稳步推进")


def get_gan_advice(gan):
    """根据天干获取五行建议。"""
    return GAN_ADVICE.get(gan, "本月宜审时度势，根据实际情况灵活应对。")


def get_enhanced_advice(ten_god, relation, gan_element, zhi_element, has_clash):
    """生成增强的流月建议。"""
    advices = []
    if relation == "喜用相关":
        advices.append("顺势而为，集中精力在最重要的事务上。")
        advices.append("主动把握机会，不要因为犹豫而错过良机。")
        advices.append("大胆推进，本月天时地利，宜积极行动。")
    elif relation == "忌神相关":
        advices.append("放慢节奏，以稳为主，不宜贪功冒进。")
        advices.append("提前做好预案，为可能出现的问题留出缓冲。")
        advices.append("保守行事，减少不必要的变动和风险。")
    else:
        advices.append("保持现状，稳步推进，不宜贸然改变方向。")
        advices.append("利用这段时间做好观察、学习和准备。")

    if has_clash:
        advices.append(CLASH_WARNING)

    return advices[:5]


def build_enhanced_month_item(month, month_name, pillar, gan, zhi, gan_element, zhi_element, ten_god, relation, branch_relations):
    """构建增强的流月数据项，匹配参考图格式。"""
    direction = get_direction(ten_god)
    events = get_enhanced_events(ten_god, relation)
    has_clash = any(r.get("type") == "六冲" for r in branch_relations)
    advices = get_enhanced_advice(ten_god, relation, gan_element, zhi_element, has_clash)
    gan_advice = get_gan_advice(gan)

    return {
        "month": month,
        "month_name": month_name,
        "pillar": pillar,
        "gan": gan,
        "zhi": zhi,
        "gan_element": gan_element,
        "zhi_element": zhi_element,
        "ten_god": ten_god,
        "relation": relation,
        "direction": direction,
        "events": events,
        "advices": advices,
        "gan_advice": gan_advice,
        "has_clash": has_clash,
        "branch_relations": branch_relations,
    }
