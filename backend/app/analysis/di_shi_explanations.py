"""十二长生词条。"""

from __future__ import annotations

DI_SHI_EXPLANATIONS = {
    "长生": "生机初现，如同婴儿诞生。代表新的开始、成长潜力，适合启动新项目。",
    "沐浴": "形骸未固，如婴儿沐浴。代表探索和尝试阶段，注意桃花和诱惑。",
    "冠带": "渐趋成熟，如少年加冠。代表知识和技能的积累阶段，适合学习进修。",
    "临官": "独立担当，如成年出仕。代表独立工作、承担责任的阶段，事业开始起步。",
    "帝旺": "鼎盛至极，精力最旺盛的阶段。代表高峰时期，适合作出重大决策，但要防盛极而衰。",
    "衰": "由盛转衰，精力开始下降。代表调整和守成的时期，不宜冒进。",
    "病": "气机衰退，如人患病。代表需要休整和调养的阶段，避免过度消耗。",
    "死": "气尽形亡，如人死亡。代表旧阶段的结束和转化，适合放下和重生。",
    "墓": "收藏归隐，如人入墓。代表积累和沉淀的阶段，适合总结和等待时机。",
    "绝": "灭绝断绝，气已尽。代表最低谷的阶段，但也是转机的开始，否极泰来。",
    "胎": "结成胎形，气开始凝聚。代表新计划的孕育阶段，需要耐心等待。",
    "养": "养育成形，如胎在母腹。代表筹备和酝酿阶段，万事俱备只欠东风。",
}

DI_SHI_LABELS = ["长生", "沐浴", "冠带", "临官", "帝旺", "衰", "病", "死", "墓", "绝", "胎", "养"]


def get_di_shi_explanation(di_shi: str) -> str:
    return DI_SHI_EXPLANATIONS.get(di_shi, "")


def get_di_shi_color(di_shi: str) -> str:
    early = ["长生", "沐浴", "冠带", "临官", "帝旺"]
    late = ["衰", "病", "死", "墓", "绝"]
    if di_shi in early:
        return "#8BA888" if di_shi in ["长生", "沐浴"] else "#B8860B"
    if di_shi in late:
        return "#B85C4A" if di_shi in ["病", "死", "绝"] else "#8C7A64"
    if di_shi in ["胎", "养"]:
        return "#7A9BAE"
    return "#8C7A64"
